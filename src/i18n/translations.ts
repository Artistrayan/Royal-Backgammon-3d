let currentLanguage: SupportedLanguage = 'en';

export function getLanguage(): SupportedLanguage {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('royal_app_lang') as SupportedLanguage;
    if (saved && TRANSLATIONS[saved]) {
      currentLanguage = saved;
    } else {
      currentLanguage = 'en';
    }
  }
  return currentLanguage;
}

export function setLanguage(lang: SupportedLanguage) {
  currentLanguage = lang;
  if (typeof window !== 'undefined') {
    localStorage.setItem('royal_app_lang', lang);
    window.dispatchEvent(new CustomEvent('app_language_changed', { detail: lang }));
  }
}

export function t(key: string, langOverride?: SupportedLanguage): string {
  const lang = langOverride || getLanguage();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
}
